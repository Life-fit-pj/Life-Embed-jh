"""행정동 이름 표기 변형. DB나 네트워크를 모르는 순수 함수만 둔다."""

import re

# 동 이름 끝의 번호. 하나(1)일 수도, 점으로 이은 여럿(6.7 · 1·2·3·4)일 수도 있다
_NUM = r"\d+(?:[.·]\d+)*"


def dong_variants(dong):
    """행정동 이름의 표기 변형을 만든다. 두 가지가 파일마다 다르다.

    ① '제' — 통계청은 '고덕제1동', 일상 표기는 '고덕1동'. 두 방향 다 만든다.
       맨 뒤의 '제N동' 만 건드린다. '홍제1동' 은 '홍1동' 이라는 없는 이름도 같이 나오는데,
       그런 줄이 어느 표에도 없어 해가 없다 — 원래 이름이 늘 같이 들어 있기 때문이다.
    ② 번호 사이의 점 — master·문화시설·점포는 '상계6.7동'(마침표), 학원·의료는 '상계6·7동'(가운뎃점).
       이걸 몰라 학원 440곳·의료 588곳이 어느 동에도 못 붙었다(2026-10-01 실측).
       숫자 사이의 점만 바꾼다 — 이름 다른 자리의 점은 안 건드린다
    """
    base = str(dong).strip()
    out = {base}

    # '고덕제1동' → '고덕1동' · '면목제3.8동' → '면목3.8동'  (맨 뒤의 '제N동' 만 건드린다)
    out.add(re.sub(rf"제({_NUM})동$", r"\1동", base))

    # '고덕1동' → '고덕제1동'  (반대 방향. 이미 '제' 가 있거나 번호 중간이면 안 붙인다)
    out.add(re.sub(rf"(?<![제\d.·])({_NUM})동$", r"제\1동", base))

    # 위에서 만든 것마다 점을 양쪽으로: '상계6.7동' ↔ '상계6·7동'
    for name in list(out):
        out.add(re.sub(r"(?<=\d)\.(?=\d)", "·", name))
        out.add(re.sub(r"(?<=\d)·(?=\d)", ".", name))

    return list(out)

